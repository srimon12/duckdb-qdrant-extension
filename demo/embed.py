#!/usr/bin/env python3
"""Embed evaluation queries with the dataset's own model and emit SQL.

The ESCI snapshot was built with intfloat/multilingual-e5-small and the
`passage: ` prefix. Queries use the matching `query: ` prefix. Same model, same
normalized 384-dimensional space as the served vectors.

FastEmbed does not ship this model, so sentence-transformers loads it directly.

Outputs, under --out:
    queries.parquet   query_id, query, embedding
    judged.parquet    query_id, product_id, gain   (E=1, S=0.1, C=0.01, I=0)
    topk.sql          dense top-10 per query, one qdrant_batch RPC
    text_topk.sql     BM25 top-10 per query, one qdrant_batch RPC
    hybrid.sql        server-side dense + BM25 fusion, one call per query
    exact.sql         exact top-10 per query in DuckDB against products
    hnsw.sql          one literal query for the duck-vss index
    demo.sql          readable output for a handful of queries

Run:
    uv run --with sentence-transformers --with pyarrow demo/embed.py --limit 50

Requires the extension to be loaded before topk.sql/text_topk.sql/hybrid.sql,
and demo/local.sql to have created the products table before exact.sql/hnsw.sql.
"""

import argparse
import json
import pathlib
import urllib.request

import pyarrow as pa
import pyarrow.parquet as pq
from sentence_transformers import SentenceTransformer

DATASET = "Qdrant/esci-products-multilingual-e5-small-embeddings"
QUERIES_URL = (
    f"https://huggingface.co/datasets/{DATASET}/resolve/main/queries.jsonl"
)
GAINS = {"E": 1.0, "S": 0.1, "C": 0.01, "I": 0.0}
LIMIT = 10


def sql_text(value):
    return "'" + value.replace("'", "''") + "'"


def vector_literal(vector):
    return "[" + ",".join(repr(float(value)) for value in vector) + "]"


def download(url, path):
    if path.exists():
        return
    request = urllib.request.Request(url, headers={"User-Agent": "qdrant-duckdb-demo"})
    with urllib.request.urlopen(request, timeout=120) as response:
        path.write_bytes(response.read())


def read_queries(path, limit):
    chosen = []
    with path.open(encoding="utf-8") as handle:
        for line in handle:
            row = json.loads(line)
            judgments = row.get("judgments") or {}
            if isinstance(judgments, list):
                pairs = [
                    (item["product_id"], item["label"]) for item in judgments
                ]
            else:
                pairs = list(judgments.items())
            pairs = [(product, label) for product, label in pairs if label in GAINS]
            if not pairs:
                continue
            chosen.append((int(row["query_id"]), row["query"], pairs))
            if len(chosen) == limit:
                break
    return chosen


def dense_sql(collection, queries, vectors, table):
    batch = json.dumps([vector.tolist() for vector in vectors], separators=(",", ":"))
    values = ", ".join(f"({index}, {query[0]})" for index, query in enumerate(queries))
    return "\n".join(
        [
            "-- generated by demo/embed.py",
            f"CREATE OR REPLACE TABLE {table} (query_id BIGINT, id VARCHAR, score DOUBLE, payload VARCHAR);",
            "-- one query_batch RPC for every query; query_index maps a row back to its query",
            f"INSERT INTO {table}",
            "SELECT q.query_id, b.id, b.score, b.payload",
            f"FROM qdrant_batch(collection := {sql_text(collection)}, "
            f"queries := {sql_text(batch)}, mode := 'dense', \"using\" := 'dense', "
            f"\"limit\" := {LIMIT}, payload_fields := 'product_id,title,brand') b",
            f"JOIN (VALUES {values}) AS q(query_index, query_id) ON q.query_index = b.query_index;",
            "",
        ]
    )


def text_sql(collection, queries, table, field):
    batch = json.dumps([text for _, text, _ in queries])
    values = ", ".join(f"({index}, {query[0]})" for index, query in enumerate(queries))
    return "\n".join(
        [
            "-- generated by demo/embed.py",
            f"CREATE OR REPLACE TABLE {table} (query_id BIGINT, id VARCHAR, score DOUBLE, payload VARCHAR);",
            "-- one query_batch RPC for every query; query_index maps a row back to its query",
            f"INSERT INTO {table}",
            "SELECT q.query_id, b.id, b.score, b.payload",
            f"FROM qdrant_batch(collection := {sql_text(collection)}, "
            f"queries := {sql_text(batch)}, mode := 'text', field := {sql_text(field)}, "
            f"k := 1.2, b := 0.75, \"limit\" := {LIMIT}, "
            "payload_fields := 'product_id,title,brand') b",
            f"JOIN (VALUES {values}) AS q(query_index, query_id) ON q.query_index = b.query_index;",
            "",
        ]
    )


def hybrid_sql(collection, queries, vectors, table, field):
    lines = [
        "-- generated by demo/embed.py",
        "-- server-side RRF over a dense prefetch and a BM25 text prefetch",
        f"CREATE OR REPLACE TABLE {table} (query_id BIGINT, id VARCHAR, score DOUBLE, payload VARCHAR);",
    ]
    for (query_id, text, _), vector in zip(queries, vectors):
        lines.append(
            f"INSERT INTO {table} SELECT {query_id}, id, score, payload FROM qdrant_hybrid_text("
            f"collection := {sql_text(collection)}, "
            f"dense_query := {vector_literal(vector)}, "
            f"text_query := {sql_text(text)}, fusion := 'rrf', dense_using := 'dense', "
            f"text_field := {sql_text(field)}, prefetch_limit := 100, "
            f'"limit" := {LIMIT}, payload_fields := \'product_id,title,brand\');'
        )
    return "\n".join(lines) + "\n"


def exact_sql(queries, vectors, dim):
    lines = [
        "-- generated by demo/embed.py; needs the products table from demo/local.sql",
        "CREATE OR REPLACE TABLE exact_topk "
        "(query_id BIGINT, product_id VARCHAR, title VARCHAR, brand VARCHAR, dist DOUBLE);",
    ]
    for (query_id, _, _), vector in zip(queries, vectors):
        literal = vector_literal(vector)
        lines.append(
            f"INSERT INTO exact_topk SELECT {query_id}, product_id, title, brand, "
            f"array_cosine_distance(emb, {literal}::FLOAT[{dim}]) AS dist "
            "FROM products ORDER BY dist LIMIT "
            f"{LIMIT};"
        )
    return "\n".join(lines) + "\n"


def hnsw_sql(query, vector, dim):
    literal = vector_literal(vector)
    distance = f"array_cosine_distance(emb, {literal}::FLOAT[{dim}])"
    return "\n".join(
        [
            "-- generated by demo/embed.py; hits the duck-vss HNSW index",
            f"-- query: {query}",
            f"EXPLAIN ANALYZE SELECT product_id, title, {distance} AS dist "
            f"FROM products ORDER BY dist LIMIT {LIMIT};",
            f"SELECT product_id, title, round({distance}, 4) AS dist "
            f"FROM products ORDER BY dist LIMIT {LIMIT};",
            "",
        ]
    )


def demo_sql(collection, queries, vectors):
    lines = [
        "-- generated by demo/embed.py",
        "-- dense, BM25, and server-side hybrid for one query each",
    ]
    for (query_id, text, _), vector in list(zip(queries, vectors))[:3]:
        lines.append(
            f"SELECT {query_id} AS query_id, {sql_text(text)} AS query, 'dense' AS leg, "
            "id, round(score, 4) AS score, payload->>'title' AS title, "
            "payload->>'brand' AS brand "
            f"FROM qdrant_query(collection := {sql_text(collection)}, "
            f"query := {vector_literal(vector)}, "
            "\"using\" := 'dense', "
            "\"limit\" := 5, payload_fields := 'product_id,title,brand');"
        )
        lines.append(
            f"SELECT {query_id} AS query_id, {sql_text(text)} AS query, 'bm25' AS leg, "
            "id, round(score, 4) AS score, payload->>'title' AS title, "
            "payload->>'brand' AS brand "
            f"FROM qdrant_text(collection := {sql_text(collection)}, "
            f"query := {sql_text(text)}, field := 'text', k := 1.2, b := 0.75, "
            "\"limit\" := 5, payload_fields := 'product_id,title,brand');"
        )
        lines.append(
            f"SELECT {query_id} AS query_id, {sql_text(text)} AS query, 'hybrid' AS leg, "
            "id, round(score, 5) AS score, payload->>'title' AS title, "
            "payload->>'brand' AS brand "
            f"FROM qdrant_hybrid_text(collection := {sql_text(collection)}, "
            f"dense_query := {vector_literal(vector)}, "
            f"text_query := {sql_text(text)}, fusion := 'rrf', "
            "dense_using := 'dense', text_field := 'text', prefetch_limit := 100, "
            "\"limit\" := 5, payload_fields := 'product_id,title,brand');"
        )
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--limit", type=int, default=50, help="number of judged queries")
    parser.add_argument("--model", default="intfloat/multilingual-e5-small")
    parser.add_argument(
        "--prefix",
        default="query: ",
        help="query prefix defined by the embedding model (E5 uses 'query: ')",
    )
    parser.add_argument("--collection", default="esci-products")
    parser.add_argument("--field", default="text", help="BM25 payload field")
    parser.add_argument("--out", type=pathlib.Path, default=pathlib.Path("out"))
    args = parser.parse_args()

    args.out.mkdir(parents=True, exist_ok=True)
    cache = args.out / "queries.jsonl"
    download(QUERIES_URL, cache)
    queries = read_queries(cache, args.limit)
    if not queries:
        raise SystemExit("no judged queries found in queries.jsonl")

    print(f"embedding {len(queries)} queries with {args.model}")
    model = SentenceTransformer(args.model)
    vectors = model.encode(
        [args.prefix + text for _, text, _ in queries],
        normalize_embeddings=True,
        show_progress_bar=False,
    )
    dim = len(vectors[0])

    judged = [
        {"query_id": query_id, "product_id": product, "gain": GAINS[label]}
        for query_id, _, pairs in queries
        for product, label in pairs
    ]
    pq.write_table(
        pa.Table.from_pylist(
            judged,
            schema=pa.schema(
                [
                    ("query_id", pa.int64()),
                    ("product_id", pa.string()),
                    ("gain", pa.float64()),
                ]
            ),
        ),
        args.out / "judged.parquet",
    )
    pq.write_table(
        pa.table(
            {
                "query_id": pa.array([q[0] for q in queries], pa.int64()),
                "query": pa.array([q[1] for q in queries], pa.string()),
                "embedding": pa.array(
                    [vector.tolist() for vector in vectors], pa.list_(pa.float32())
                ),
            }
        ),
        args.out / "queries.parquet",
    )

    (args.out / "topk.sql").write_text(
        dense_sql(args.collection, queries, vectors, "qdrant_topk"), encoding="utf-8"
    )
    (args.out / "text_topk.sql").write_text(
        text_sql(args.collection, queries, "text_topk", args.field), encoding="utf-8"
    )
    (args.out / "hybrid.sql").write_text(
        hybrid_sql(args.collection, queries, vectors, "hybrid_topk", args.field),
        encoding="utf-8",
    )
    (args.out / "exact.sql").write_text(
        exact_sql(queries, vectors, dim), encoding="utf-8"
    )
    (args.out / "hnsw.sql").write_text(
        hnsw_sql(queries[0][1], vectors[0], dim), encoding="utf-8"
    )
    (args.out / "demo.sql").write_text(
        demo_sql(args.collection, queries, vectors), encoding="utf-8"
    )

    print(f"dimensions: {dim}")
    print(f"judged pairs: {len(judged)}")
    print(f"wrote: {args.out}/{{topk,text_topk,hybrid,exact,hnsw,demo}}.sql")
    print(f"wrote: {args.out}/{{queries,judged}}.parquet")


if __name__ == "__main__":
    main()
